int ops_ready;
static int opcmp(const void* a, const void* b) {
    const Op *x = a, *y = b;
    return y->bits - x->bits;
}
void ops_init(void) {
    int n = 0;
    for (; ops[n].pat; n++) {
        u64 m = 0, v = 0;
        int bits = 0;
        for (int i = 0; i < 16; i++) {
            char ch = ops[n].pat[i];
            u64 bit = 1ull << (63 - i);
            if (ch == '0' || ch == '1') {
                m |= bit;
                bits++;
                if (ch == '1') v |= bit;
            }
        }
        ops[n].mask = m;
        ops[n].val = v;
        ops[n].bits = bits;
    }
    qsort(ops, n, sizeof(Op), opcmp);
    ops_ready = 1;
}
static const Op* op_nop;
/* EXIT.FCSM_TR after VOTE.VTG is a hw cull exit; treat as NOP or the VS never writes position */
const Op* decode(u64 w) {
    for (int i = 0; ops[i].pat; i++)
        if ((w & ops[i].mask) == ops[i].val) {
            if (ops[i].id == O_EXIT && ((w & 31) == 0x1c)) {
                if (!op_nop)
                    for (int k = 0; ops[k].pat; k++)
                        if (ops[k].id == O_NOP) {
                            op_nop = &ops[k];
                            break;
                        }
                if (op_nop) return op_nop;
            }
            return &ops[i];
        }
    return NULL;
}
